// Submit contact messages through FormSubmit without leaving the portfolio.
contactForm.addEventListener('submit', async (event) => {
    event.preventDefault();

    const submitButton = contactForm.querySelector('button[type="submit"]');
    const originalText = submitButton.textContent;
    submitButton.textContent = 'Sending...';
    submitButton.disabled = true;

    try {
        const formData = new FormData(contactForm);
        const subject = formData.get('subject');
        formData.set('_subject', `New portfolio message: ${subject}`);

        const response = await fetch(contactForm.action, {
            method: 'POST',
            body: formData,
            headers: { Accept: 'application/json' }
        });

        if (!response.ok) {
            throw new Error('The message service returned an error.');
        }

        showNotification('Your message was sent successfully.', 'success');
        contactForm.reset();
    } catch (error) {
        // Fall back to a regular form post if the browser blocks the AJAX request.
        contactForm.action = contactForm.action.replace('/ajax/', '/');
        HTMLFormElement.prototype.submit.call(contactForm);
        return;
    } finally {
        submitButton.textContent = originalText;
        submitButton.disabled = false;
    }
});

// Smooth scrolling for navigation links
navLinks.forEach(link => {
    link.addEventListener('click', (e) => {
        const targetId = link.getAttribute('href');
        
        // Only prevent default and handle smooth scrolling for internal anchor links
        if (targetId.startsWith('#')) {
            e.preventDefault();
            const targetSection = document.querySelector(targetId);
            
            if (targetSection) {
                const offsetTop = targetSection.offsetTop - 70; // Account for fixed navbar
                window.scrollTo({
                    top: offsetTop,
                    behavior: 'smooth'
                });
            }
        }
        // For external links (like resume.html), let the default behavior work
    });
});

